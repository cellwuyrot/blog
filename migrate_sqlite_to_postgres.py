"""One-time offline copy; does not delete or modify SQLite or uploaded files."""
import os, sqlite3, sys
from pathlib import Path
import psycopg

def env_file():
 p=Path(__file__).resolve().parent/'.env'
 if p.exists():
  for line in p.read_text().splitlines():
   if line.strip() and not line.lstrip().startswith('#') and '=' in line:
    k,v=line.split('=',1);os.environ.setdefault(k.strip(),v.strip().strip('"\''))

def main():
 env_file(); url=os.getenv('DATABASE_URL','').strip()
 if not url.startswith(('postgresql://','postgres://')): raise SystemExit('Set DATABASE_URL in .env or environment.')
 path=Path(os.environ.get('DATA_DIR',Path(__file__).resolve().parent/'data'))/'site.sqlite3'
 if not path.is_file(): raise SystemExit('SQLite database not found; no files were changed: '+str(path))
 source=sqlite3.connect('file:'+str(path.resolve())+'?mode=ro',uri=True)
 try:
  projects=source.execute('SELECT id,slug,data,updated FROM projects ORDER BY id').fetchall()
  settings=source.execute('SELECT key,value FROM settings').fetchall()
 finally:source.close()
 with psycopg.connect(url) as db:
  with db.cursor() as c:
   c.execute('SELECT pg_advisory_xact_lock(71513983)')
   c.execute('CREATE TABLE IF NOT EXISTS projects (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slug TEXT UNIQUE NOT NULL, data TEXT NOT NULL, updated BIGINT NOT NULL)')
   c.execute('CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL)')
   c.execute('SELECT (SELECT count(*) FROM projects), (SELECT count(*) FROM settings)')
   if any(c.fetchone()): raise RuntimeError('Target database is not empty. Migration stopped without overwriting anything.')
   c.executemany('INSERT INTO projects (id,slug,data,updated) VALUES (%s,%s,%s,%s)',projects)
   c.executemany('INSERT INTO settings (key,value) VALUES (%s,%s)',settings)
   if projects:c.execute("SELECT setval(pg_get_serial_sequence('projects','id'), %s, true)",(max(row[0] for row in projects),))
 print(f'Copied {len(projects)} publications and {len(settings)} settings. SQLite and uploads were not changed.')
if __name__=='__main__':main()
